#!/usr/bin/env node
// Update the EVE tools in this folder to the newest EVE, without touching your app or plan.
//   node eve/update.mjs            update
//   node eve/update.mjs --check    only say whether a newer EVE is out
//   node eve/update.mjs --from <folder>   update from a local copy of the ItsyBIT EVE Template instead of GitHub
//
// Replaced: eve/, .claude/skills/eve-*/, AGENTS.md and sample/ (EVE's own files).
// Never touched: app/ and plan/ (yours). One exception: app/lib/gwt.mjs and app/lib/store.js are
// copies of the sample's helpers, so they're updated too, but only if you never changed them.

import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";

const REPO = "jocelynenglund/itsybit-eve-template";
const BRANCH = "main";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
const fromIdx = args.indexOf("--from");
const from = fromIdx >= 0 ? path.resolve(args[fromIdx + 1] || ".") : null;

// EVE's own files. A path is managed if it's one of these files or inside one of these folders.
const MANAGED_FILES = ["AGENTS.md"];
const MANAGED_DIRS = ["eve/", "sample/"];
const isSkill = p => /^\.claude\/skills\/eve-[^/]+\//.test(p);
const managed = p => MANAGED_FILES.includes(p) || MANAGED_DIRS.some(d => p.startsWith(d)) || isSkill(p);
// Copied into app/ by eve-build; updated only while still identical to the old sample copy.
const COPIED = { "app/lib/gwt.mjs": "sample/todo/app/lib/gwt.mjs", "app/lib/store.js": "sample/todo/app/lib/store.js" };
// Generated by `node eve/test.mjs`: never worth reporting or deleting.
const generated = p => p.endsWith("/plan/built.json") || p.includes("/plan/.built/") || p.includes("/node_modules/");

function readLocal(dir) {
  const files = new Map();
  (function walk(rel) {
    const abs = path.join(dir, rel);
    if (!fs.existsSync(abs)) return;
    for (const d of fs.readdirSync(abs, { withFileTypes: true })) {
      const p = rel ? rel + "/" + d.name : d.name;
      if (d.isDirectory()) { if (d.name !== ".git" && d.name !== "node_modules") walk(p); }
      else if (d.isFile()) files.set(p, fs.readFileSync(path.join(dir, p)));
    }
  })("");
  return files;
}

// A GitHub tarball: gzip around a tar. Read files out of it with nothing but Node.
function untar(buf) {
  const files = new Map();
  let pos = 0, longName = null, paxPath = null;
  const str = (b, s, n) => b.subarray(s, s + n).toString("utf8").replace(/\0.*$/s, "");
  while (pos + 512 <= buf.length) {
    const h = buf.subarray(pos, pos + 512);
    if (h.every(b => b === 0)) break;
    const size = parseInt(str(h, 124, 12).trim() || "0", 8);
    const type = String.fromCharCode(h[156] || 48);
    let name = str(h, 0, 100);
    const prefix = str(h, 345, 155);
    if (prefix) name = prefix + "/" + name;
    const body = buf.subarray(pos + 512, pos + 512 + size);
    pos += 512 + Math.ceil(size / 512) * 512;
    if (type === "L") { longName = body.toString("utf8").replace(/\0.*$/s, ""); continue; }
    if (type === "x") { const m = body.toString("utf8").match(/\d+ path=([^\n]*)\n/); paxPath = m ? m[1] : null; continue; }
    if (type === "g") continue;
    name = paxPath || longName || name; paxPath = longName = null;
    if (type !== "0" && type !== "\0") continue;
    files.set(name.split("/").slice(1).join("/"), Buffer.from(body)); // drop the "<repo>-<sha>/" folder
  }
  return files;
}

async function readUpstream() {
  if (from) return readLocal(from);
  const url = `https://codeload.github.com/${REPO}/tar.gz/refs/heads/${BRANCH}`;
  let res;
  try { res = await fetch(url); } catch (e) { fail(`Couldn't reach GitHub (${e.cause?.code || e.message}). Are you online?`); }
  if (!res.ok) fail(`GitHub answered ${res.status} for ${url}.`);
  return untar(zlib.gunzipSync(Buffer.from(await res.arrayBuffer())));
}

function fail(msg) { console.error(msg); process.exit(1); }
const versionFile = files => { try { return JSON.parse(files.get("eve/version.json")); } catch { return null; } };
const versionOf = files => (versionFile(files) || {}).version || null;
// "2026-11-01.10" is newer than "2026-11-01.9": compare the date, then the release number.
const versionKey = v => { const m = /^(\d{4}-\d{2}-\d{2})(?:\.(\d+))?/.exec(v || ""); return m ? [m[1], +(m[2] || 1)] : ["", 0]; };
const newer = (a, b) => { const x = versionKey(a), y = versionKey(b); return x[0] !== y[0] ? x[0] > y[0] : x[1] > y[1]; };
// Release notes for everything newer than the version you had (the newest three if it's unknown).
function whatsNew(had) {
  const rel = (versionFile(upstream) || {}).releases || [];
  const list = had ? rel.filter(r => newer(r.version, had)) : rel.slice(0, 3);
  return list.flatMap(r => (r.notes || []).map(n => `  - ${n} (${r.version})`));
}
const same = (a, b) => a && b && Buffer.compare(a, b) === 0;

const upstream = await readUpstream();
if (!upstream.has("eve/book.html")) fail("That doesn't look like the ItsyBIT EVE Template (no eve/book.html).");
const local = readLocal(root);
const was = versionOf(local), now = versionOf(upstream);

const changed = [], added = [], removed = [], helpers = [], kept = [];
for (const [p, body] of upstream) {
  if (!managed(p) || generated(p)) continue;
  if (!local.has(p)) added.push(p);
  else if (!same(local.get(p), body)) changed.push(p);
}
for (const p of local.keys()) if (managed(p) && !generated(p) && !upstream.has(p)) removed.push(p);
for (const [mine, sample] of Object.entries(COPIED)) {
  const oldCopy = local.get(sample), newCopy = upstream.get(sample), yours = local.get(mine);
  if (!yours || !newCopy || same(yours, newCopy)) continue;
  if (same(yours, oldCopy)) helpers.push(mine); else kept.push(mine);
}

const label = v => v ? `EVE ${v}` : "an older EVE";
if (!changed.length && !added.length && !removed.length && !helpers.length) {
  console.log(`You have the newest EVE${now ? ` (${now})` : ""}. Nothing to update.`);
  process.exit(0);
}
if (checkOnly) {
  console.log(`A newer EVE is out: ${label(was)} → ${label(now)} (${changed.length + added.length + removed.length + helpers.length} files). Run: node eve/update.mjs`);
  const notes = whatsNew(was); if (notes.length) console.log("What's new:\n" + notes.join("\n"));
  process.exit(0);
}

const write = (p, body) => { const abs = path.join(root, p); fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.writeFileSync(abs, body); };
for (const p of [...changed, ...added]) write(p, upstream.get(p));
for (const p of helpers) write(p, upstream.get(COPIED[p]));
for (const p of removed) {
  fs.rmSync(path.join(root, p));
  for (let d = path.dirname(path.join(root, p)); d.startsWith(root + path.sep) && fs.readdirSync(d).length === 0; d = path.dirname(d)) fs.rmdirSync(d);
}

console.log(`Updated EVE: ${label(was)} → ${label(now)}. Your app/ and plan/ weren't touched.`);
{ const notes = whatsNew(was); if (notes.length) console.log("What's new:\n" + notes.join("\n")); }
const list = (title, xs) => xs.length && console.log(`${title}:\n  ${xs.join("\n  ")}`);
list("Changed", changed); list("New", added); list("Removed", removed); list("Updated helpers in app/lib (you hadn't changed them)", helpers);
list(`Kept your own version (yours differs from EVE's; compare with ${"sample/todo/app/lib/"})`, kept);
console.log("Next: run `node eve/test.mjs` to check your app still passes, and restart `node eve/serve.mjs` if it's running.");
